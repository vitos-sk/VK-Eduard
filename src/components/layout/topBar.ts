/**
 * Угол шапки на телефоне — значок чатов и аватар — стоит в оболочке (`TopBarCorner`) и не пересоздаётся
 * при переходах, как нижняя панель: иначе на каждом переходе фото аватара на миг показывало инициалы.
 * Он есть только на главных экранах; у вложенных страниц своя шапка со стрелкой «назад».
 *
 * Отдельный файл без `"use client"`: список берёт и серверный код (шапка главной).
 */
const TOP_BAR_ROUTES: readonly string[] = ["/", "/objects", "/hours", "/reports", "/dashboard"];

/** Нужен ли на этой странице угол шапки (значок чатов и аватар). */
export function hasTopBarCorner(pathname: string): boolean {
  return TOP_BAR_ROUTES.includes(pathname);
}

/**
 * Правый отступ шапки под угол на телефоне: 16 (край) + 72 (две кнопки по 32 и зазор 8) + 8 воздуха.
 * На компьютере угла нет (там боковая панель), отступ не нужен.
 */
export const TOP_BAR_CORNER_PAD = "max-lg:pr-24";
