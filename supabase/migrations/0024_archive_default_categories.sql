-- Стандартні категорії робіт («Плоскі дахи», «EPDM», «Інше» та інші зі стартового набору 0015) більше не потрібні:
-- у формі звіту лишаються тільки ті, які шеф додав сам у «Налаштуваннях». Нічого не видаляємо, а архівуємо —
-- звіти, що на них посилаються, лишаються цілими, а шеф за потреби поверне будь-яку з архіву.
update work_categories
set archived_at = coalesce(archived_at, now())
where label in (
  'Плоскі дахи', 'Скатні дахи', 'EPDM', 'Resitrix', 'Рубероїд', 'Дахівка / черепиця',
  'Фасадні роботи', 'Жерстяні роботи', 'Водостоки', 'Демонтаж', 'Ремонт даху', 'Склад',
  'Додаткові роботи', 'Інше'
);
